"""Train a small MNIST MLP, quantize it to int8 for the accelerator, export it.

    python model/mnist.py            (MNIST_DIR = folder with mnist_train.csv / mnist_test.csv)

Network: 784 -> 64 (ReLU) -> 10. After float training it is quantized the
way the accelerator computes:
  x_q  = pixel // 2                       int8 input, 0..127   (scale s_x = 2/255)
  W_q  = round(W / s_w),  s_w = max|W| / 127                    (per layer)
  h_q  = requant(x_q @ W1_q + b1_q)  with mult/2^shift = s_x*s_w1/s_h, ReLU
  logits = h_q @ W2_q + b2_q             int32 ACC, argmax (no requant needed)
The int8 network is evaluated bit-exactly with model/golden.py, and
sw/mnist_data.h gets the weights (in the accelerator's strip layout), test
images and the predictions the SoC must reproduce exactly.
"""

import json
import os
from pathlib import Path

import numpy as np
import torch
from torch import nn

import golden

ROOT = Path(__file__).resolve().parent.parent
MNIST_DIR = Path(os.environ.get("MNIST_DIR", Path.home() / "Downloads" / "project2"))
N_EXPORT = 32                      # test images run on the SoC


def load(split: str):
    raw = np.loadtxt(MNIST_DIR / f"mnist_{split}.csv", delimiter=",", skiprows=1, dtype=np.int64)
    return raw[:, 1:], raw[:, 0]


def train(Xtr, ytr, epochs=8, seed=0):
    torch.manual_seed(seed)
    net = nn.Sequential(nn.Linear(784, 64), nn.ReLU(), nn.Linear(64, 10))
    opt = torch.optim.Adam(net.parameters(), lr=1e-3)
    X = torch.tensor(Xtr / 255.0, dtype=torch.float32)
    y = torch.tensor(ytr)
    for ep in range(epochs):
        perm = torch.randperm(len(X))
        for i in range(0, len(X), 128):
            idx = perm[i:i + 128]
            loss = nn.functional.cross_entropy(net(X[idx]), y[idx])
            opt.zero_grad()
            loss.backward()
            opt.step()
    return net


def mult_shift(scale: float):
    """mult / 2^shift ~= scale, with mult as large as fits in 16 bits."""
    shift = int(np.floor(np.log2(65535 / scale)))
    return int(round(scale * 2**shift)), shift


def quantize(net, Xcal):
    W1 = net[0].weight.detach().numpy().T          # [784, 64]
    b1 = net[0].bias.detach().numpy()
    W2 = net[2].weight.detach().numpy().T          # [64, 10]
    b2 = net[2].bias.detach().numpy()
    s_x = 2 / 255
    s_w1 = np.abs(W1).max() / 127
    s_w2 = np.abs(W2).max() / 127
    h = np.maximum(Xcal / 255.0 @ W1 + b1, 0)
    s_h = np.percentile(h, 99.9) / 127
    mult, shift = mult_shift(s_x * s_w1 / s_h)
    return dict(
        W1=np.round(W1 / s_w1).astype(np.int64), b1=np.round(b1 / (s_x * s_w1)).astype(np.int64),
        W2=np.round(W2 / s_w2).astype(np.int64), b2=np.round(b2 / (s_h * s_w2)).astype(np.int64),
        mult=mult, shift=shift)


def int8_forward(q, X):
    """Bit-exact model of what the SoC computes. Returns (h_q, logits)."""
    xq = X // 2
    h = golden.layer(xq, q["W1"], q["b1"], q["mult"], q["shift"], relu=True)
    logits = golden.wrap32(h.astype(np.int64) @ q["W2"] + q["b2"])
    return h, logits


def strips(W, n_pad):
    """[K, N] -> [N/8][K][8] (zero-padded to n_pad columns): the WBUF layout."""
    K, N = W.shape
    Wp = np.zeros((K, n_pad), np.int64)
    Wp[:, :N] = W
    return Wp.reshape(K, n_pad // 8, 8).transpose(1, 0, 2)


def c_array(ctype, name, a, per_line=24):
    flat = [str(int(v)) for v in np.asarray(a).ravel()]
    body = ",\n".join("    " + ", ".join(flat[i:i + per_line]) for i in range(0, len(flat), per_line))
    return f"static const {ctype} {name}[{len(flat)}] __attribute__((aligned(4))) = {{\n{body}\n}};\n"


def export(q, Xte, yte, preds):
    b2 = np.zeros(16, np.int64)
    b2[:10] = q["b2"]
    h = (ROOT / "sw" / "mnist_data.h")
    h.write_text(
        "// mnist_data.h — generated by model/mnist.py; do not edit\n#pragma once\n#include <stdint.h>\n\n"
        f"#define MNIST_N {N_EXPORT}\n#define L1_MULT {q['mult']}u\n#define L1_SHIFT {q['shift']}u\n\n"
        + c_array("int8_t", "W1p", strips(q["W1"], 64))
        + c_array("int32_t", "B1", q["b1"])
        + c_array("int8_t", "W2p", strips(q["W2"], 16))
        + c_array("int32_t", "B2", b2)
        + c_array("int8_t", "IMAGES", Xte[:N_EXPORT] // 2)
        + c_array("uint8_t", "LABELS", yte[:N_EXPORT])
        + c_array("uint8_t", "EXPECTED", preds[:N_EXPORT]))
    print("wrote", h)


def main():
    Xtr, ytr = load("train")
    Xte, yte = load("test")
    net = train(Xtr, ytr)
    with torch.no_grad():
        float_acc = (net(torch.tensor(Xte / 255.0, dtype=torch.float32)).argmax(1).numpy()
                     == yte).mean()
    q = quantize(net, Xtr[:2000])
    _, logits = int8_forward(q, Xte)
    preds = logits.argmax(1)
    int8_acc = (preds == yte).mean()
    res = {"float_accuracy": float(float_acc), "int8_accuracy": float(int8_acc),
           "l1_mult": q["mult"], "l1_shift": q["shift"],
           "exported_images": N_EXPORT,
           "exported_correct": int((preds[:N_EXPORT] == yte[:N_EXPORT]).sum())}
    print(json.dumps(res, indent=2))
    (ROOT / "model" / "mnist_results.json").write_text(json.dumps(res, indent=2) + "\n")
    export(q, Xte, yte, preds)


if __name__ == "__main__":
    main()
